/* ===========================================================================
   THE ATMOSPHERE — one plane, every page, the whole viewport
   ---------------------------------------------------------------------------
   One full-screen triangle, one fragment shader, no geometry and no textures:
   every value in here is computed, so nothing is downloaded and nothing is
   generated by a model.

   It used to render behind the hero of one page and nowhere else, which meant
   the most expensive and the best-looking thing on the site was visible for
   about one screenful and then thrown away on the way to Selected Work. It is
   now mounted on the fixed atmosphere plane the base template already puts on
   every page, so the room the site is read in is the same room from the first
   scroll to the footer — and it answers to the document rather than to one
   section:

     the aurora        a domain-warped flow field, drifting on its own clock
     the aperture      an iris that tightens as the document is read
     the interference  a fine signal, refracted where the field is strongest
     the motes         a sparse specular grid, brightest near the light
     the key           a directional light the pointer leads, never follows

   It renders BEHIND pages that are already complete without it. Every caller
   gate lives in site.js; this module assumes it was allowed to run and only
   worries about running cheaply and stopping cleanly.
   =========================================================================== */

import { Renderer, Program, Mesh, Triangle } from 'ogl';

const VERT = /* glsl */ `
attribute vec2 uv;
attribute vec2 position;
varying vec2 vUv;
void main() {
  vUv = uv;
  gl_Position = vec4(position, 0.0, 1.0);
}
`;

/* Value noise, hashed from the fragment's own coordinates, and an fbm built
   from it. Three octaves plus one warp is the cheapest thing that still reads
   as weather rather than as television static. */
const FRAG = /* glsl */ `
precision highp float;

varying vec2 vUv;

uniform float uTime;
uniform vec2  uRes;
uniform vec2  uPointer;   // -1..1, eased, the light direction
uniform float uScroll;    // 0..1 through the whole document
uniform vec3  uAccent;    // the page's own accent
uniform vec3  uCobalt;
uniform vec3  uTeal;
uniform float uFade;      // master, so the plane can arrive and leave politely
uniform vec2  uTune;      // x: interference tightness, y: refraction softness
uniform float uGain;      // the one master: how loud the plane is
uniform float uLift;      // and how much louder it is allowed to be in a hero

float hash(vec2 p) {
  p = fract(p * vec2(123.34, 456.21));
  p += dot(p, p + 45.32);
  return fract(p.x * p.y);
}

float vnoise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(
    mix(hash(i + vec2(0.0, 0.0)), hash(i + vec2(1.0, 0.0)), u.x),
    mix(hash(i + vec2(0.0, 1.0)), hash(i + vec2(1.0, 1.0)), u.x),
    u.y
  );
}

float fbm(vec2 p) {
  float a = 0.5;
  float v = 0.0;
  for (int i = 0; i < 3; i++) {
    v += a * vnoise(p);
    p = p * 2.03 + 19.19;
    a *= 0.5;
  }
  return v;
}

void main() {
  // Aspect-correct coordinates, origin at centre.
  float aspect = uRes.x / max(uRes.y, 1.0);
  vec2 p = (vUv - 0.5) * vec2(aspect, 1.0);

  float t = uTime * 0.035;

  // --- the aurora ---------------------------------------------------------
  // A flow field warped by a second field. The whole thing drifts upward and
  // sideways at different rates, so it never repeats inside a visit and never
  // reads as a looping texture.
  // The frequencies matter more than they look: p spans about ±0.9 on a wide
  // desktop, so a field sampled at 1.0 puts the entire viewport inside a
  // single noise cell and draws one flat, almost-black wash. These are chosen
  // so a 16:9 screen holds three or four bands of it.
  vec2 q = vec2(fbm(p * 2.6 + vec2(0.0, t)),
                fbm(p * 2.6 + vec2(5.2, 1.3) - t * 0.7));
  vec2 r = vec2(fbm(p * 3.4 + q * 1.9 + vec2(1.7, 9.2) + t * 0.9),
                fbm(p * 3.4 + q * 1.9 + vec2(8.3, 2.8) - t * 0.6));
  float aurora = fbm(p * 2.2 + r * 1.7);
  // fbm here runs roughly 0.28 to 0.62, so the window is placed over that
  // rather than over the theoretical 0..1 the octaves could reach.
  aurora = smoothstep(0.26, 0.62, aurora);

  // Two bands out of the same field, separated so the room has a warm side
  // and a cool side rather than one flat wash.
  float bandA = pow(aurora, 1.35);
  float bandB = pow(smoothstep(0.30, 0.86, aurora + r.y * 0.30), 1.7);

  // --- the aperture -------------------------------------------------------
  // A soft iris whose centre is nudged by the pointer, and whose edge
  // tightens as the document is read. Light passing through a precision
  // instrument: the opening does not follow the cursor, the refraction across
  // it does.
  vec2  centre = vec2(0.16, 0.02) + uPointer * 0.06;
  float rad    = length((p - centre) * vec2(0.86, 1.0));
  float iris   = smoothstep(1.02 * uTune.y, 0.12, rad);

  float ringR  = mix(0.70, 0.34, uScroll);
  float ring   = smoothstep(0.020, 0.0, abs(rad - ringR)) * 0.42;

  // --- directional key ----------------------------------------------------
  vec2  lightDir = normalize(vec2(-0.55, 0.83) + uPointer * 0.45);
  float key      = clamp(dot(normalize(p - centre + 1e-4), lightDir), 0.0, 1.0);
  key            = pow(key, 2.2);

  // --- the interference ---------------------------------------------------
  // Fine horizontal signal, bent by the iris so it refracts through the field
  // rather than sliding over it.
  float bend  = iris * 0.14 * uTune.y;
  float n     = vnoise(vec2(p.x * 2.4 + t, p.y * 3.1 - t * 0.6));
  n           = mix(n, vnoise(vec2(p.x * 6.7 - t * 1.4, p.y * 7.3 + t)), 0.42);
  float lines = sin((p.y + bend * n * 2.0) * (232.0 * uTune.x) + n * 5.4 - uTime * 0.22);
  float sig   = smoothstep(0.94, 1.0, lines) * iris * (0.24 + 0.34 * n);

  // --- the motes ----------------------------------------------------------
  // A sparse specular grid: most cells are dark, a few carry a slow pulse, and
  // the ones nearest the light are the ones that catch. Cheap, and it gives
  // the plane something to do at the far edges where the aurora has fallen off.
  vec2  cell = p * 9.0;
  vec2  cid  = floor(cell);
  float seed = hash(cid);
  vec2  cf   = fract(cell) - 0.5 - (vec2(hash(cid + 3.1), hash(cid + 7.7)) - 0.5) * 0.7;
  float mote = smoothstep(0.16, 0.0, length(cf));
  mote *= step(0.86, seed) * (0.45 + 0.55 * sin(uTime * 0.5 + seed * 43.0));
  mote *= 0.35 + 0.65 * key;

  // --- assembly -----------------------------------------------------------
  vec3 col = vec3(0.0);
  col += uAccent * bandA * (0.150 + 0.130 * key);
  col += uCobalt * bandB * 0.155;
  col += uTeal   * aurora * iris * 0.080;
  col += uAccent * iris  * (0.075 + 0.105 * key);
  col += uTeal   * sig   * 0.42;
  col += uAccent * ring  * 0.34;
  col += mix(uAccent, vec3(1.0), 0.55) * mote * 0.16;

  // Depth, not decoration: the field falls away toward the edges of frame so
  // the plane never becomes a rectangle of glow sitting on top of the page —
  // but it falls away late, because a wash that dies at 40% of the radius is
  // a vignette with a dot in it rather than weather.
  float vign = smoothstep(1.72, 0.10, length(p));
  col *= vign;

  // Two numbers, and only two. The terms above are ratios between the layers;
  // uGain is the level the plane reads at while somebody is *reading*, and
  // uLift is how much louder it is allowed to be over the top of a page that
  // has a hero to justify it. A full-strength interference field behind a
  // paragraph is a plane that has stopped being a room and started being a
  // competitor, so the lift is spent by the time the hero has scrolled away —
  // which is the same thing the aperture is already doing, said in brightness
  // instead of in radius. A page with no hero passes a lift of 1 and simply
  // never has the loud version.
  col *= uFade * uGain * mix(uLift, 1.0, smoothstep(0.0, 0.26, uScroll));

  // Dither, so a very dark gradient does not band on an 8-bit display. It is
  // added after the gain, because a dither the gain multiplies is not a dither
  // any more — it is grain.
  col += (hash(gl_FragCoord.xy + uTime) - 0.5) * (1.6 / 255.0);

  gl_FragColor = vec4(col, 1.0);
}
`;

function rgb(css, fallback) {
  const m = String(css).trim().match(/^#?([0-9a-f]{6})$/i);
  if (m) {
    const v = parseInt(m[1], 16);
    return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
  }
  const p = String(css).match(/-?[\d.]+/g);
  if (p && p.length >= 3) return [p[0] / 255, p[1] / 255, p[2] / 255];
  return fallback;
}

export function mount(canvas, opts) {
  const options = opts || {};
  const host = canvas.parentElement || canvas;
  const styles = getComputedStyle(document.body);

  /* Below native resolution, deliberately, and on every device.

     Nothing this plane draws has a hard edge: it is an aurora, a soft iris and
     a fine interference field, all of them low-frequency and all of them
     scaled up by the compositor for free. Rendering it at device pixel ratio
     1.5 was paying four times the fragment cost of 0.75 for a difference
     nobody can point at — and that was when it drew behind one hero on one
     page. Now that it is the room every page is read in, the same saving is
     the whole site's, on every device, for the whole visit. A phone renders
     fewer pixels still, because it has fewer to spare. */
  const lean = window.innerWidth < 900;

  const renderer = new Renderer({
    canvas,
    alpha: false,
    antialias: false,
    depth: false,
    stencil: false,
    powerPreference: 'low-power',
    dpr: Math.min(window.devicePixelRatio || 1, lean ? 0.7 : 1),
  });
  const gl = renderer.gl;
  gl.clearColor(0, 0, 0, 1);

  const program = new Program(gl, {
    vertex: VERT,
    fragment: FRAG,
    uniforms: {
      uTime: { value: 0 },
      uRes: { value: [1, 1] },
      uPointer: { value: [0, 0] },
      uScroll: { value: 0 },
      uAccent: { value: rgb(styles.getPropertyValue('--accent'), [0.09, 0.63, 0.56]) },
      uCobalt: { value: rgb(styles.getPropertyValue('--cobalt'), [0.30, 0.44, 0.91]) },
      uTeal: { value: rgb(styles.getPropertyValue('--teal'), [0.09, 0.63, 0.56]) },
      uFade: { value: 0 },
      uTune: { value: [1, 1] },
      uGain: { value: options.gain || 3.2 },
      uLift: { value: options.lift || 1 },
    },
  });
  const mesh = new Mesh(gl, { geometry: new Triangle(gl), program });

  let raf = 0;
  let running = false;
  let visible = true;
  let dead = false;
  const target = [0, 0];
  const eased = [0, 0];
  let t0 = 0;
  let live = false;
  let scrollTo = 0;
  /* Where the light is going, and where it currently is. A page or a section
     change moves the target; the frame loop walks the uniforms toward it, so
     the room changes at the same speed the accent interpolates rather than
     cutting between two rooms. */
  const accentTo = program.uniforms.uAccent.value.slice();
  const tuneTo = [1, 1];

  function size() {
    const w = host.clientWidth || window.innerWidth;
    const h = host.clientHeight || window.innerHeight;
    renderer.setSize(w, h);
    program.uniforms.uRes.value = [gl.drawingBufferWidth, gl.drawingBufferHeight];
  }

  /* The plane is fixed to the viewport, so how far through the document you
     are is the only reading of "scroll" that means anything to it. */
  function readScroll() {
    const doc = document.documentElement;
    const span = doc.scrollHeight - window.innerHeight;
    scrollTo = span > 40 ? Math.min(1, Math.max(0, (doc.scrollTop || document.body.scrollTop) / span)) : 0;
  }

  /* Thirty frames a second, not sixty. Nothing on this plane moves fast: the
     aurora drifts on a clock measured in tens of seconds and the interference
     crawls. Half the frames are indistinguishable and cost exactly as much, and
     this is now running on every page rather than behind one hero — so the
     saving is the whole site's, on every device, for no visible difference. */
  const MIN_FRAME = 1000 / 30;
  let lastDraw = 0;

  function frame(now) {
    if (dead) return;
    raf = requestAnimationFrame(frame);
    if (now - lastDraw < MIN_FRAME) return;
    lastDraw = now;
    if (!t0) t0 = now;
    const time = (now - t0) / 1000;

    // Pointer is eased hard: the light drifts toward where you are, it never
    // snaps to it, and it never tracks like a blob.
    eased[0] += (target[0] - eased[0]) * 0.045;
    eased[1] += (target[1] - eased[1]) * 0.045;

    for (let i = 0; i < 3; i++) {
      program.uniforms.uAccent.value[i] += (accentTo[i] - program.uniforms.uAccent.value[i]) * 0.06;
    }
    program.uniforms.uTune.value[0] += (tuneTo[0] - program.uniforms.uTune.value[0]) * 0.06;
    program.uniforms.uTune.value[1] += (tuneTo[1] - program.uniforms.uTune.value[1]) * 0.06;
    program.uniforms.uScroll.value += (scrollTo - program.uniforms.uScroll.value) * 0.08;

    program.uniforms.uTime.value = time;
    program.uniforms.uPointer.value = eased;
    program.uniforms.uFade.value = Math.min(1, program.uniforms.uFade.value + 0.02);

    renderer.render({ scene: mesh });

    /* The plane declares itself live only once it has actually drawn a frame.
       Doing it at mount time instead put the class on in the same task that
       created the element, so the browser had never resolved the opacity:0 it
       was meant to be coming up from — and the fade-in never ran. */
    if (!live) {
      live = true;
      canvas.classList.add('is-live');
    }
  }

  function play() {
    if (running || dead || !visible) return;
    running = true;
    raf = requestAnimationFrame(frame);
  }
  function pause() {
    running = false;
    cancelAnimationFrame(raf);
    raf = 0;
  }

  function onPointer(ev) {
    target[0] = (ev.clientX / Math.max(window.innerWidth, 1)) * 2 - 1;
    target[1] = 1 - (ev.clientY / Math.max(window.innerHeight, 1)) * 2;
  }
  function onScroll() {
    readScroll();
    /* With no pointer to lead the light, the document leads it instead: on a
       phone the room still answers to the one input everybody has. */
    if (!window.matchMedia || !window.matchMedia('(pointer: fine)').matches) {
      target[0] = Math.sin(scrollTo * 6.283) * 0.5;
      target[1] = 1 - scrollTo * 2;
    }
  }
  function onVisibility() {
    if (document.hidden) pause();
    else play();
  }
  function onLost(ev) {
    ev.preventDefault();
    destroy();
    if (options.onLost) options.onLost();
  }

  size();
  readScroll();
  window.addEventListener('resize', size, { passive: true });
  window.addEventListener('pointermove', onPointer, { passive: true });
  window.addEventListener('scroll', onScroll, { passive: true });
  document.addEventListener('visibilitychange', onVisibility);
  canvas.addEventListener('webglcontextlost', onLost, false);
  window.addEventListener('pagehide', destroy, { once: true });
  play();

  function destroy() {
    if (dead) return;
    dead = true;
    pause();
    window.removeEventListener('resize', size);
    window.removeEventListener('pointermove', onPointer);
    window.removeEventListener('scroll', onScroll);
    document.removeEventListener('visibilitychange', onVisibility);
    canvas.removeEventListener('webglcontextlost', onLost);
    const ext = gl.getExtension('WEBGL_lose_context');
    if (ext) ext.loseContext();
    canvas.classList.remove('is-live');
  }

  /* The one thing the outside world may say to this plane: which colour the
     room is in. It never asks who is asking, and it never reaches back into
     the document to find out. */
  function tune(opts2) {
    if (dead || !opts2) return;
    if (opts2.accent) {
      const c = rgb(opts2.accent, accentTo);
      accentTo[0] = c[0];
      accentTo[1] = c[1];
      accentTo[2] = c[2];
    }
    if (opts2.optics) {
      tuneTo[0] = opts2.optics.interference || 1;
      tuneTo[1] = opts2.optics.refraction || 1;
    }
  }

  return { destroy, tune };
}

export default { mount };
